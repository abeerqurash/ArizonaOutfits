// navbar-cover

const pagewrapperSection = document.querySelector(".page-wrapper");
const navCover = document.querySelector(".navigation-cover");
const navbar = document.querySelector(".navbar");

window.addEventListener("scroll", () => {
    const pagewrapperHeight = pagewrapperSection.offsetHeight;
    const scrollPosition = window.scrollY;

    if (scrollPosition > pagewrapperHeight / 2) {
        navCover.classList.add("active");
        navbar.classList.add("scrolled");
    } else {
        navCover.classList.remove("active");
        navbar.classList.remove("scrolled");
    }
});

